export function getCountryTimezone(country) {
  if (!country) return 'Asia/Beirut';
  return COUNTRY_TIMEZONES[country] || 'Asia/Beirut';
}

/**
 * Returns current day of week ('Sunday'..'Saturday') and current time string ('HH:mm')
 * evaluated in the target country's local timezone.
 */
export function getStoreLocalTime(country) {
  const timeZone = getCountryTimezone(country);
  const now = new Date();

  try {
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone,
      weekday: 'long',
      hour: '2-digit',
      minute: '2-digit',
      hourCycle: 'h23'
    });

    const partsMap = {};
    formatter.formatToParts(now).forEach(p => {
      partsMap[p.type] = p.value;
    });

    let hourStr = partsMap.hour || '00';
    if (hourStr === '24') hourStr = '00';

    return {
      day: partsMap.weekday || 'Monday',
      timeStr: `${hourStr.padStart(2, '0')}:${(partsMap.minute || '00').padStart(2, '0')}`
    };
  } catch (e) {
    const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
    const currentDay = days[now.getDay()];
    const currentHour = now.getHours().toString().padStart(2, '0');
    const currentMin = now.getMinutes().toString().padStart(2, '0');
    return {
      day: currentDay,
      timeStr: `${currentHour}:${currentMin}`
    };
  }
}

/**
 * Determines whether a store is currently open given its openingHours schedule
 * and store country (which determines its local timezone).
 */
export function checkIfStoreOpen(openingHours, country) {
  if (!openingHours || !Array.isArray(openingHours) || openingHours.length === 0) {
    return true;
  }

  const { day: currentDay, timeStr: currentTimeStr } = getStoreLocalTime(country);
  const hoursToday = openingHours.find(h => h.day === currentDay);

  if (!hoursToday || !hoursToday.isOpen) {
    return false;
  }

  const { open, close } = hoursToday;
  if (!open || !close) return true;

  if (open <= close) {
    return currentTimeStr >= open && currentTimeStr <= close;
  } else {
    // Overnight hours (e.g. 18:00 to 02:00)
    return currentTimeStr >= open || currentTimeStr <= close;
  }
}
